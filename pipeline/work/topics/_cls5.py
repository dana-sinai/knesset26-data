def pick(rules,t):
    for pat,p,s in rules:
        if re.search(pat,t): return p,s
    return None
def classify(title):
    t=re.sub(r'^הצעת חוק ','',title.strip())
    t=re.sub(r'^לתיקון ','',t)
    r=pick(SPECIAL,t)
    if r: return r+('S',)
    if TAXLAW.match(t):
        if LOCAL.match(t):
            if re.search(r'מעונות סטודנטים|מוסדות להכשרה|מכללה|בתי ספר|בית ספר|מעון',t): return ('local','education','L')
            if re.search(r'נכים|מוגבלות|נפש|דרי רחוב',t): return ('local','welfare','L')
            if re.search(r'בית מדרש|בתי עלמין',t): return ('local','religion','L')
            if re.search(r'חיילים',t): return ('local','security','L')
            if re.search(r'ערים קולטות',t): return ('local','immigration','L')
            if re.search(r'השואה',t): return ('local','welfare','L')
            if re.search(r'באזור',t): return ('local','settlement','L')
            return ('local','economy','L')
        r=pick(TAXSPEC,t)
        if r: return r+('T',)
        law=t.split('(')[0]
        sub=t[len(law):] if re.match(r'^(פקודת )?מס הכנסה',t) else t
        r=pick(TAXDOM,sub)
        if r: return r+('X',)
        return ('economy','','XD')
    r=pick(GENERAL,t)
    if r: return r+('G',)
    return ('other','','D')
